// One-off: Natural Earth 1:110m countries (public domain) → assets/countries.geojson
// (slim, 3-decimal coords) + src/data/countries.ts (id, iso, name, label point).
// Run: deno run -A scripts/build-geo.ts
import type * as GeoJSON from "geojson";
const URL_NE =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson";
type P = Record<string, string | number>;
const ne = await (await fetch(URL_NE)).json() as GeoJSON.FeatureCollection<GeoJSON.Geometry, P>;
const round = (c: unknown): unknown =>
  Array.isArray(c) ? (typeof c[0] === "number" ? c.map((n: number) => Math.round(n * 1000) / 1000) : c.map(round)) : c;
const rows: string[] = [];
const features = ne.features.map((f, id) => {
  const p = f.properties;
  const iso = [p.ISO_A2_EH, p.ISO_A2].map(String).find((v) => v !== "-99") ?? `X${id}`;
  const name = String(p.NAME);
  const iso3 = [p.ISO_A3_EH, p.ISO_A3, p.ADM0_A3].map(String).find((v) => v !== "-99") ?? "";
  rows.push(
    `  [${JSON.stringify(iso)}, ${JSON.stringify(name)}, ${p.LABEL_X}, ${p.LABEL_Y}, ${JSON.stringify(iso3)}],`,
  );
  const g = f.geometry as GeoJSON.Polygon;
  return {
    type: "Feature",
    id,
    properties: { id, iso, name },
    geometry: { type: g.type, coordinates: round(g.coordinates) },
  };
});
await Deno.writeTextFile("assets/countries.geojson", JSON.stringify({ type: "FeatureCollection", features }));
await Deno.writeTextFile(
  "src/data/countries.ts",
  `// Generated by scripts/build-geo.ts from Natural Earth (public domain). Index = place id.
export type Country = { iso: string; name: string; lon: number; lat: number; iso3: string };
const RAW: [string, string, number, number, string][] = [
${rows.join("\n")}
];
export const COUNTRIES: Country[] = RAW.map(([iso, name, lon, lat, iso3]) => ({ iso, name, lon, lat, iso3 }));
export const BY_ISO: Record<string, number> = Object.fromEntries(COUNTRIES.map((c, i) => [c.iso, i]));
export const BY_ISO3: Record<string, number> = Object.fromEntries(COUNTRIES.map((c, i) => [c.iso3, i]));
`,
);
