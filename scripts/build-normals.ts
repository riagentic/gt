// One-off: daily temperature normals → src/data/normals.ts, so the live anomaly compares ERA5 with ERA5.
// Open-Meteo archive (ERA5, 0.25°), 6 years spaced evenly over 1991–2020: their mean year is 2005.5, the centre of
// the WMO 1991–2020 normal, so a linear warming trend cancels. A 3-harmonic fit of ~2,200 days per point gives a
// smooth seasonal cycle. Free tier ≈ 26 calls per point-year (264 requests ≈ 6,900 calls): throttled under the
// 5,000/hour limit, ~1.5 h. Responses are cached in .aio/normals-cache, so a rerun resumes.
// Run: deno task normals
import { CLIMATE } from "../src/data/climate.ts";
import { BY_ISO, COUNTRIES } from "../src/data/countries.ts";
import { HARMONICS, yearFrac } from "../src/lib/world.ts";

const YEARS = [1993, 1998, 2003, 2008, 2013, 2018];
const GAP_MS = 22_000; // ≈164 requests/hour × 26 calls
const CACHE = ".aio/normals-cache";
const OUT = "src/data/normals.ts";

type Day = [t: number, temp: number]; // t = fraction of the year, 0…1

let last = 0;
async function year(iso: string, lon: number, lat: number, y: number): Promise<Day[]> {
  const file = `${CACHE}/${iso}-${y}.json`;
  let body = await Deno.readTextFile(file).catch(() => "");
  if (!body) {
    await new Promise((r) => setTimeout(r, Math.max(0, last + GAP_MS - Date.now())));
    for (let attempt = 0;; attempt++) {
      last = Date.now();
      const res = await fetch(
        `https://archive-api.open-meteo.com/v1/archive?latitude=${lat.toFixed(2)}&longitude=${lon.toFixed(2)}` +
          `&start_date=${y}-01-01&end_date=${y}-12-31&daily=temperature_2m_mean&models=era5&timezone=GMT`,
      );
      const text = await res.text();
      // A 200 can still carry an error ("Unexpected error while streaming data"): only real JSON gets cached.
      if (res.ok && text.startsWith("{")) {
        body = text;
        break;
      }
      const why = `${res.status} ${text.slice(0, 200)}`;
      if (res.ok && attempt < 5) {
        console.warn(`${iso} ${y}: bad body (${why}), retrying`);
        continue;
      }
      if (res.status !== 429 || attempt >= 5) throw new Error(`${iso} ${y}: ${why}`);
      console.warn(`${iso} ${y}: rate limited, waiting 10 min`);
      await new Promise((r) => setTimeout(r, 600_000));
    }
    await Deno.writeTextFile(file, body);
  }
  const d = JSON.parse(body).daily;
  return (d.time as string[]).flatMap((t, i) => {
    const v = d.temperature_2m_mean[i];
    return typeof v === "number" ? [[yearFrac(t), v] as Day] : [];
  });
}

/** Least squares for T(t) = a0 + Σ aₖcos(2πkt) + bₖsin(2πkt): normal equations, Gaussian elimination. */
function fit(days: Day[]): number[] {
  const row = (
    t: number,
  ) => [
    1,
    ...Array.from(
      { length: HARMONICS },
      (_, k) => [Math.cos(2 * Math.PI * (k + 1) * t), Math.sin(2 * Math.PI * (k + 1) * t)],
    ).flat(),
  ];
  const n = 1 + 2 * HARMONICS;
  const A = Array.from({ length: n }, () => new Array(n + 1).fill(0));
  for (const [t, v] of days) {
    const r = row(t);
    for (let i = 0; i < n; i++) {
      for (let j = 0; j < n; j++) A[i][j] += r[i] * r[j];
      A[i][n] += r[i] * v;
    }
  }
  for (let c = 0; c < n; c++) {
    const p = A.slice(c).reduce((b, r, i) => (Math.abs(r[c]) > Math.abs(A[b][c]) ? c + i : b), c);
    [A[c], A[p]] = [A[p], A[c]];
    for (let r = 0; r < n; r++) {
      if (r === c) continue;
      const f = A[r][c] / A[c][c];
      for (let k = c; k <= n; k++) A[r][k] -= f * A[c][k];
    }
  }
  return A.map((r, i) => Math.round((r[n] / r[i]) * 1000) / 1000);
}

await Deno.mkdir(CACHE, { recursive: true });
const out: Record<string, number[]> = {};
for (const iso of CLIMATE) {
  const c = COUNTRIES[BY_ISO[iso]];
  const days: Day[] = [];
  for (const y of YEARS) days.push(...await year(iso, c.lon, c.lat, y)); // sequential: one shared throttle
  if (days.length < 300 * YEARS.length) throw new Error(`${iso}: only ${days.length} days`);
  out[iso] = fit(days);
  console.log(`${iso} ${c.name}: mean ${out[iso][0]}°C (${days.length} days)`);
}

await Deno.writeTextFile(
  OUT,
  `// Generated by scripts/build-normals.ts — do not edit. ERA5 daily mean 2 m temperature, 1991–2020 normal
// (years ${YEARS.join(", ")}), as ${HARMONICS}-harmonic coefficients [a0, a1, b1, …] per country label point.
export const NORMALS: Record<string, number[]> = ${JSON.stringify(out)};\n`,
);
console.log(`→ ${OUT} (${Object.keys(out).length} points)`);
